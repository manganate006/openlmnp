    <h3>Plan d'amortissement</h3>
    <p>Cet onglet déroule, pour chaque élément du bien (composants, travaux, mobilier, frais d'acquisition), son amortissement année par année, de la mise en service à la fin du plan. Cliquez sur un élément pour ouvrir son tableau. L'année en cours est surlignée.</p>

    <h3>Refaire une dotation à la main</h3>
    <ul>
        <li data-icon="&#x1F4B6;"><strong>Annuité pleine</strong> &mdash; la valeur brute divisée par la durée.</li>
        <li data-icon="&#x1F4C5;"><strong>Première année</strong> &mdash; l'annuité pleine multipliée par le prorata affiché : les jours restants dans l'année, jour de mise en service compris, sur 365 (366 une année bissextile). Un élément mis en service le 1er juillet 2025 prend 184/365.</li>
        <li data-icon="&#x1F501;"><strong>Années suivantes</strong> &mdash; l'annuité pleine.</li>
        <li data-icon="&#x2795;"><strong>Dernière année</strong> &mdash; quand la mise en service n'est pas un 1er janvier, le plan dure un exercice de plus : il reprend la part retirée la première année. Au terme, l'amortissement cumulé égale la valeur brute.</li>
    </ul>

    <h3>Les colonnes</h3>
    <ul>
        <li data-icon="&#x1F4C9;"><strong>Dotation</strong> &mdash; l'annuité du plan pour l'exercice.</li>
        <li data-icon="&#x2705;"><strong>Déduction</strong> &mdash; « déductible » au régime réel. Avant votre premier exercice au réel, l'annuité est <strong>réputée pratiquée</strong> : elle compte dans le cumul, mais ne se déduit pas.</li>
        <li data-icon="&#x1F4CA;"><strong>Amortissement cumulé</strong> et <strong>reste à amortir</strong> &mdash; à la clôture de l'exercice. Si vous avez repris un dossier existant, la première ligne porte le cumul de votre comptabilité antérieure.</li>
    </ul>

    <div class="ctx-tip" style="margin-top:12px;">
        <strong>Les mêmes chiffres que la liasse :</strong> pour un exercice donné, l'annexe « Détail des immobilisations » du PDF et de l'écran Télédéclaration reprend la ligne de ce tableau (dotation, cumul, reste à amortir).
    </div>

    <div class="ctx-warning" style="margin-top:12px;">
        <strong>Déductible ne veut pas dire déduit en totalité.</strong> L'amortissement ne peut pas créer de déficit : l'excédent est différé (art. 39 C du CGI) et reporté sur les exercices suivants. Ce report se calcule pour l'ensemble du bien, pas élément par élément : il se lit dans la liasse (ligne 318 du 2033-B et suivi des amortissements différés).
    </div>
