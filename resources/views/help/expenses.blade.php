    <h3>Gestion des charges</h3>
    <p>Toutes les dépenses liées à votre activité de location meublée sont déductibles du résultat fiscal.</p>

    <h3>Types de charges</h3>
    <ul>
        <li data-icon="&#x1F3E0;"><strong>Charge dédiée</strong> &mdash; 100 % liée à la location (ménage Airbnb, linge, consommables). Déduite intégralement.</li>
        <li data-icon="&#x1F504;"><strong>Charge partagée</strong> &mdash; Partagée avec votre usage personnel (électricité, internet, assurance). La quote-part s'applique automatiquement.</li>
    </ul>

    <h3>Charges courantes</h3>
    <ul>
        <li data-icon="&#x1F4CB;"><strong>Taxe foncière</strong> &mdash; Charge partagée, au prorata de la quote-part</li>
        <li data-icon="&#x1F50C;"><strong>Énergie</strong> &mdash; Électricité, gaz, eau</li>
        <li data-icon="&#x1F6E1;"><strong>Assurances</strong> &mdash; Habitation, PNO, RC</li>
        <li data-icon="&#x1F9F9;"><strong>Entretien</strong> &mdash; Ménage, petites réparations</li>
        <li data-icon="&#x1F4BB;"><strong>Frais divers</strong> &mdash; Comptabilité, abonnements, déplacements</li>
    </ul>

    <h3>Charges récurrentes</h3>
    <p>Le champ <strong>Récurrence</strong> décrit une échéance, pas un total : le montant que vous saisissez est celui d'<strong>un</strong> prélèvement.</p>
    <ul>
        <li data-icon="&#x1F5D3;"><strong>Mensuel</strong> ou <strong>Trimestriel</strong> &mdash; Le bouton <strong>« Générer les échéances »</strong>, sur la ligne de la charge dans la liste, crée les échéances manquantes jusqu'au 31 décembre de la même année.</li>
        <li data-icon="&#x1F4C5;"><strong>Annuel</strong> et <strong>Ponctuel</strong> &mdash; Une seule ligne dans l'exercice. Pour la reporter sans tout retaper, le bouton <strong>« Dupliquer »</strong> recopie la charge : il ne reste qu'à confirmer la description, la date et le montant.</li>
    </ul>
    <p>Chaque échéance générée est une charge à part entière : ajustez son montant s'il a varié, et joignez-lui son propre justificatif &mdash; ceux de la charge d'origine ne sont pas recopiés.</p>

    <div class="ctx-tip">
        <strong>Bon à savoir :</strong> la génération ne déborde jamais sur l'année suivante (un exercice est une année civile) et refuse d'écrire dans un exercice clôturé. Relancée deux fois, elle ne crée pas de doublon : les dates déjà occupées sont laissées telles quelles.
    </div>

    <h3>Charge ou travaux ?</h3>
    <p>Les <strong>petites réparations</strong> (volet roulant, serrure, robinet, prise électrique...) sont des charges directes en catégorie « Entretien ». Elles sont déduites intégralement l'année de la dépense.</p>
    <p>En revanche, les <strong>gros travaux</strong> qui augmentent la valeur du bien (rénovation complète, isolation, nouvelle salle de bain...) doivent être enregistrés dans l'onglet <strong>Travaux</strong> du bien et sont amortis sur 10 à 15 ans.</p>

    <h3>Joindre un justificatif</h3>
    <p>Dépliez la section <strong>Pièces justificatives</strong>, cliquez sur
    <strong>« Ajouter un document »</strong> puis déposez votre fichier. Le <strong>libellé se
    remplit tout seul</strong> avec le nom du fichier : vous pouvez le remplacer, mais vous
    n'avez plus à y penser. Un libellé vide empêchait l'enregistrement, et le message d'erreur
    restait invisible tant que la section était repliée.</p>

    <h3>Retrouver un justificatif déjà déposé</h3>
    <p>Les pièces jointes vivent dans la section <strong>Justificatifs</strong> de la charge, repliée par
    défaut : dépliez-la pour les voir. Chaque fichier peut être <strong>ouvert</strong> dans un nouvel
    onglet ou <strong>téléchargé</strong> depuis sa vignette.</p>
    <p>La liste des charges peut aussi afficher une colonne <strong>Docs</strong>, qui compte les pièces
    de chaque ligne. Elle est masquée par défaut : activez-la par le bouton de choix des colonnes, en
    haut à droite du tableau.</p>

    <div class="ctx-warning">
        <strong>Important :</strong> Conservez tous les justificatifs pendant 6 ans minimum (10 ans recommandés). Joignez-les directement à chaque charge.
    </div>
