    <h3>Gestion des recettes</h3>
    <p>Enregistrez ici tous les loyers perçus via Airbnb, Booking ou en direct.</p>

    <h3>Saisie des recettes</h3>
    <ul>
        <li data-icon="&#x1F4B0;"><strong>Montant</strong> &mdash; Le montant <strong>brut</strong> payé par le voyageur, avant la commission de la plateforme (TTC pour un bien assujetti à la TVA)</li>
        <li data-icon="&#x1F4B3;"><strong>Commission plateforme</strong> &mdash; Ce que la plateforme a retenu sur ce loyer, tel qu'indiqué sur votre relevé. Le net encaissé est calculé tout seul</li>
        <li data-icon="&#x1F4C5;"><strong>Date</strong> &mdash; Date d'encaissement du loyer</li>
        <li data-icon="&#x1F3E0;"><strong>Bien</strong> &mdash; Le bien concerné par cette recette</li>
        <li data-icon="&#x1F4CE;"><strong>Justificatif</strong> &mdash; Joignez le relevé ou la facture plateforme</li>
    </ul>

    <h3>Import CSV</h3>
    <p>Plutôt que de saisir manuellement, vous pouvez importer un fichier CSV depuis Airbnb via le menu <strong>Import Airbnb</strong>. Les doublons sont détectés automatiquement.</p>
    <p>Vous pouvez aussi déposer le <strong>rapport annuel de revenus</strong> de la plateforme dans <strong>Importer un justificatif</strong> : il crée une recette par mois loué, au montant brut, commission enregistrée à part.</p>
    <div class="ctx-warning">
        <strong>Un seul des deux chemins.</strong> Le CSV et le relevé annuel portent les mêmes euros, l'un par réservation, l'autre par mois. Les importer tous les deux compte votre année en double &mdash; et comme les montants ne coïncident jamais, la détection de doublons ne peut rien y voir.
    </div>

    <h3>Sur la liasse</h3>
    <p>Les loyers bruts vont en ligne <strong>218</strong> du 2033-B (hors taxe pour un bien assujetti à la TVA), et les commissions en ligne <strong>242</strong>, autres charges externes, retenues en totalité : elles ne concernent que la location, la quote-part de surface ne s'y applique pas. Le résultat est le même que si l'on déclarait les loyers nets.</p>
    <div class="ctx-warning">
        <strong>Une commission, un seul endroit.</strong> Si la commission figure déjà sur la recette, ne la saisissez pas aussi en charge « Commissions plateformes » : elle serait déduite deux fois. Cette catégorie de charge sert aux frais facturés à part, sans recette correspondante (abonnement à un logiciel de gestion des annonces, par exemple).
    </div>

    <div class="ctx-warning">
        <strong>Attention :</strong> Ne pas inclure la taxe de séjour dans les recettes &mdash; elle est collectée pour le compte de la commune et n'est pas un revenu.
    </div>
</div>
