    <h3>L'adresse du bien</h3>
    <p>Commencez &agrave; taper l'adresse&nbsp;: les propositions de la <strong>Base Adresse Nationale</strong> apparaissent, et en choisir une remplit d'un coup l'adresse, le <strong>code postal</strong> et la <strong>commune</strong>. Vous pouvez tout saisir &agrave; la main&nbsp;: rien n'en d&eacute;pend, et si le service ne r&eacute;pond pas, vous n'avez simplement aucune proposition.</p>

    <h3>Et le chiffrement des justificatifs ?</h3>
    <p>Ne vous en préoccupez pas maintenant. Le <strong>coffre-fort</strong> (menu <strong>Paramètres</strong>) chiffre le contenu de vos justificatifs et des photos de biens avec une phrase de passe que vous seul connaissez. Il s'active <strong>quand vous voulez</strong> : les fichiers déjà déposés sont chiffrés à ce moment-là, rien ne se perd à attendre.</p>

    <div class="ctx-warning">
        <strong>Si vous l'avez d&eacute;j&agrave; activ&eacute;</strong>, vous pouvez d&eacute;poser la photo m&ecirc;me coffre verrouill&eacute;&nbsp;: le chiffrement n'a besoin que de la moiti&eacute; publique de votre cl&eacute;. C'est seulement pour la <em>revoir</em> ensuite que votre phrase de passe vous sera demand&eacute;e.
