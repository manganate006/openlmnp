    <h3>Gestion des emprunts</h3>
    <p>Renseignez vos prêts immobiliers pour que les intérêts et l'assurance emprunteur soient automatiquement déduits en charges.</p>

    <h3>Informations à saisir</h3>
    <ul>
        <li data-icon="&#x1F4B5;"><strong>Capital emprunté</strong> &mdash; Montant total du prêt</li>
        <li data-icon="&#x1F4C8;"><strong>Taux d'intérêt</strong> &mdash; Taux nominal annuel</li>
        <li data-icon="&#x1F4C5;"><strong>Durée</strong> &mdash; Nombre de mois du prêt</li>
        <li data-icon="&#x1F6E1;"><strong>Assurance</strong> &mdash; Montant mensuel de l'assurance emprunteur</li>
    </ul>

    <h3>Ce qui est déductible</h3>
    <p>Seuls les <strong>intérêts d'emprunt</strong> et l'<strong>assurance emprunteur</strong> sont déductibles (pas le capital remboursé). La quote-part surface s'applique si le bien est partiellement loué.</p>
    <p>Sur la liasse, ils ne vont pas sur la même ligne du 2033-B : les intérêts en <strong>294</strong> (charges financières), l'assurance emprunteur en <strong>242</strong> (autres charges externes), comme toute prime d'assurance.</p>

    <h3>Frais d'emprunt</h3>
    <p>Les <strong>frais de dossier, de courtage, ou la part non restituable d'une caution</strong> sont déductibles (art. 39-1-1° quater du CGI). Par défaut, ils sont déduits <strong>en une fois</strong> l'année de leur paiement (ligne <strong>242</strong>, comme l'assurance emprunteur).</p>
    <p>Vous pouvez opter pour un <strong>étalement linéaire</strong> sur la durée du prêt, depuis votre profil (section « Frais d'emprunt »). Les frais étalés vont alors en ligne <strong>294</strong>, comme les intérêts. Cette option est <strong>globale</strong> (tous vos emprunts, présents et futurs) et <strong>irrévocable pendant 2 ans</strong> une fois exercée : réfléchissez-y avant de l'activer.</p>

    <h3>Emprunt dédié</h3>
    <p>Si un emprunt finance <strong>exclusivement</strong> le logement loué (ex : prêt travaux du studio indépendant, distinct du prêt de la résidence principale), cochez <strong>« Emprunt dédié à ce logement »</strong> &mdash; les intérêts et l'assurance sont alors déduits à 100 %, sans quote-part. Un emprunt qui finance l'achat de toute la propriété reste proratisé.</p>

    <h3>Tableau d'amortissement</h3>
    <p>Le tableau d'amortissement est calculé automatiquement. Vous pouvez le consulter en détail en cliquant sur un emprunt.</p>

    <div class="ctx-tip">
        <strong>Astuce :</strong> Les intérêts sont plus élevés en début de prêt, ce qui maximise la déduction fiscale les premières années.
    </div>
</div>
