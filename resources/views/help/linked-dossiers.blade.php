    <h3>Qu'est-ce qu'un dossier lié ?</h3>
    <p>Un dossier lié est un dossier d'indivision <strong>offert</strong> : un compte à part entière, séparé
        du vôtre, que vous ouvrez par une simple bascule depuis votre compte principal — sans mot de passe à
        retenir, sans adresse e-mail à créer. Il est réservé aux indivisions <strong>entre personnes
        physiques</strong> (nature juridique 2110 au registre Sirene) : le bien et ses indivisaires s'y
        déclarent, et une seule liasse est produite au nom de l'indivision, avec répartition du résultat
        entre indivisaires (annexe 2031 bis-SD).</p>
    <p>L'indivision ne demande <strong>pas d'abonnement à part</strong>&nbsp;: il suffit qu'un indivisaire soit abonné. Chacun garde son propre abonnement pour les biens qu'il loue seul. Si aucun indivisaire n'est abonné (par exemple entre héritiers), l'indivision se tient dans un compte ordinaire, avec son propre abonnement&nbsp;: activez alors la rubrique &laquo;&nbsp;Indivision&nbsp;&raquo; de son profil.</p>

    <h3>Le créer</h3>
    <p>Depuis « Dossiers liés » (menu Paramètres), indiquez le SIREN de l'indivision : il est vérifié dans la
        base Sirene (nature juridique, établissement actif). Le SIREN et le caractère « indivision » de ce
        dossier sont figés dès cette vérification et ne peuvent plus être modifiés ensuite — c'est ce qui
        garantit que la liasse porte bien le SIREN de l'indivision.</p>

    <h3>L'ouvrir et en revenir</h3>
    <p>Un sélecteur apparaît dans le menu, en haut à droite, dès qu'un dossier lié existe. L'ouvrir vous y
        authentifie directement ; un bandeau plein reste affiché en permanence pour le rappeler — nom du
        dossier, SIREN, et un bouton « Revenir à mon dossier » — complété d'une carte d'identité en tête de la
        barre latérale et d'un rappel sur la barre d'actions des formulaires de saisie : impossible de
        confondre ce dossier avec le vôtre. <strong>Il n'existe aucune connexion directe à un dossier
        lié</strong> : ni mot de passe, ni réinitialisation ne permettent d'y entrer autrement que par cette
        bascule.</p>
    <p><strong>Plusieurs onglets ouverts ?</strong> La bascule vaut pour tout le navigateur. Un onglet resté
        sur l'ancien dossier ne peut plus rien enregistrer : à la première action, une fenêtre « Vous avez
        changé de dossier dans un autre onglet » l'indique, rien n'est enregistré, et le bouton « Recharger
        la page » le remet sur le dossier ouvert. C'est voulu : sans cela, une saisie faite dans cet onglet
        partirait dans le mauvais dossier.</p>

    <h3>Ce qui est séparé, ce qui ne l'est pas</h3>
    <ul>
        <li data-icon="&#x1F4C1;">Biens, recettes, charges, emprunts, justificatifs, coffre-fort, badges : propres à chaque dossier.</li>
        <li data-icon="&#x1F511;">Clé d'intelligence artificielle, avis, mode de navigation : ceux de votre compte principal, quel que soit le dossier ouvert.</li>
        <li data-icon="&#x1F510;">Jetons MCP : créés uniquement depuis votre compte principal (la page « Jetons MCP » est fermée tant que vous êtes dans un dossier lié), mais un jeton peut être rattaché à un dossier — voir ci-dessous.</li>
        <li data-icon="&#x1F465;">Le dossier est partagé entre indivisaires : chacun l'ouvre depuis son propre compte, tant qu'il reste actif.</li>
    </ul>

    <h3>Un jeton MCP pour un dossier</h3>
    <p>Depuis « Jetons MCP » (menu Paramètres), un nouveau jeton peut être créé « pour » un dossier dont
        vous êtes membre actif, plutôt que pour votre compte personnel : un assistant IA connecté avec ce
        jeton consulte et modifie alors les données <strong>du dossier</strong>, jamais les vôtres. Le jeton
        reste le vôtre (vous seul pouvez le révoquer, et il compte dans votre quota de jetons) ; seul le
        dossier qu'il vise change.</p>
    <p>Son accès au dossier est <strong>revérifié à chaque appel</strong> : s'il n'y a plus de membre actif,
        si le dossier est archivé ou fermé, ou (pour un accès gratuit d'indivisaire) si plus aucun membre
        abonné ou en compte standard n'y reste, le jeton répond une <strong>erreur explicite</strong> plutôt
        que de retomber en silence sur vos propres données.</p>

    <h3>Inviter le second indivisaire</h3>
    <p>Depuis la fiche du dossier, saisissez son adresse électronique et cliquez sur « Inviter » : un
        courriel lui parvient avec un lien personnel, valable 14 jours. <strong>Rejoindre un dossier ne
        consomme aucune offre</strong> — seule la création d'un dossier en consomme une.</p>
    <p>Pour l'accepter, la personne invitée doit se connecter avec <strong>la même adresse électronique</strong>
        que celle invitée, sur un compte actif : ni suspendu, ni de démonstration, ni lui-même un dossier
        lié. Si elle n'a pas encore de compte, le lien le lui explique et lui propose soit de créer un compte
        payant (abonnement), soit un <strong>accès gratuit d'indivisaire</strong> — voir ci-dessous.</p>
    <p>Une invitation peut être <strong>relancée</strong> (l'ancien lien cesse aussitôt de fonctionner) ou
        <strong>révoquée</strong> tant qu'elle n'a pas été acceptée.</p>

    <h3>Un indivisaire sans biens à lui</h3>
    <p>Un héritier, un conjoint ou une compagne sans location meublée personnelle n'a aucune raison de payer un
        abonnement pour accéder au seul dossier d'indivision partagé avec vous. Sur le lien d'invitation, la
        personne qui n'a pas encore de compte peut cliquer sur « Créer mon accès gratuit d'indivisaire » :
        elle choisit un nom et un mot de passe, <strong>l'adresse électronique est celle de l'invitation et ne
        peut pas être modifiée</strong>. Le compte est créé, connecté et rattaché au dossier en une seule
        étape, même si l'instance n'accepte pas d'inscription libre.</p>
    <ul>
        <li data-icon="&#x1F512;">Ce compte ne possède <strong>jamais de dossier à lui</strong> : à la
            connexion, il arrive directement dans son dossier lié (ou sur la liste « Dossiers liés » s'il en
            a plusieurs), et ne peut pas saisir de biens dans son propre espace.</li>
        <li data-icon="&#x26A0;&#xFE0F;">Ce dossier reste accessible à ce compte <strong>tant qu'il reste au
            moins un autre membre actif, abonné ou en compte standard</strong>. Si tous les autres membres se
            résilient, l'accès de ce compte se ferme aussi — un dossier gratuit ne peut pas se perpétuer sans
            personne pour le faire vivre.</li>
        <li data-icon="&#x1F91D;">Ce compte ne devient jamais responsable du dossier (inviter, révoquer,
            archiver) : si vous résiliez ou quittez, l'administration passe à un autre membre abonné ou en
            compte standard — jamais à un accès gratuit d'indivisaire.</li>
        <li data-icon="&#x2B06;&#xFE0F;">Si la personne s'abonne un jour, son compte devient un compte
            ordinaire sans rien perdre : elle garde son accès à ce dossier.</li>
    </ul>

    <h3>Quitter, révoquer, et la suite en cas de résiliation</h3>
    <ul>
        <li data-icon="&#x1F6AA;">Chaque indivisaire peut <strong>quitter</strong> le dossier à tout moment.
            Le propriétaire peut <strong>révoquer</strong> l'accès d'un autre membre.</li>
        <li data-icon="&#x1F512;">Chacun garde l'accès au dossier tant que <strong>son propre compte</strong>
            reste actif — l'état des autres indivisaires n'y change rien.</li>
        <li data-icon="&#x1F501;">Si le créateur du dossier résilie son abonnement ou quitte le dossier,
            l'administration (inviter, révoquer, archiver) passe automatiquement à un autre membre actif.</li>
        <li data-icon="&#x1F4E6;">Si plus aucun membre n'est actif, le dossier n'est <strong>jamais
            supprimé</strong> : il reste en l'état, simplement inaccessible, jusqu'à ce qu'un membre
            redevienne actif.</li>
    </ul>

    <div class="ctx-tip">
        <strong>Astuce :</strong> le nombre de dossiers que vous pouvez créer dépend de votre abonnement
        (illimité en auto-hébergement, sauf réglage contraire de l'administrateur de l'instance). Archiver un
        dossier ne supprime rien de ses données, mais ferme l'accès : plus personne ne peut l'ouvrir ensuite.
    </div>
