    <h3>Simulateur micro-BIC vs régime réel</h3>
    <p>Comparez les deux régimes fiscaux pour déterminer lequel est le plus avantageux pour votre situation.</p>

    <h3>Les deux régimes</h3>
    <ul>
        <li data-icon="&#x1F4CA;"><strong>Micro-BIC</strong> &mdash; Abattement forfaitaire de 50 % (location meublée de longue durée, ou meublé de tourisme classé) ou 30 % (meublé de tourisme non classé). Simple mais souvent moins avantageux.</li>
        <li data-icon="&#x1F4C8;"><strong>Régime réel</strong> &mdash; Déduction des charges réelles + amortissements. Plus avantageux quand les amortissements sont élevés.</li>
    </ul>
    <p>Pour une <strong>indivision</strong>, le micro-BIC suit les mêmes règles que pour un dossier individuel&nbsp;: son plafond se compte sur la totalité des recettes de l'indivision. Une indivision gérée en commun peut, en droit, former une société de fait exclue du micro-BIC (Conseil d'État du 14/11/2025, n° 495516)&nbsp;: faites valider votre situation par un expert-comptable avant de l'appliquer.</p>

    <h3>Comment lire les résultats</h3>
    <ul>
        <li data-icon="&#x2705;"><strong>Économie</strong> &mdash; La différence entre les deux régimes. Si positive, le réel est plus avantageux.</li>
        <li data-icon="&#x1F4B0;"><strong>Base imposable</strong> &mdash; Le montant soumis à l'impôt dans chaque régime</li>
    </ul>

    <h3>Filtres</h3>
    <p>Sélectionnez l'année et le bien pour affiner la simulation. Les données sont calculées à partir de vos recettes, charges et amortissements réels.</p>

    <h3>Repère de loyer du marché</h3>
    <p>
        Quand la commune d'un bien est connue (après un clic sur « Estimer (DVF) » sur sa fiche),
        le simulateur affiche un repère de loyer &mdash; la « Carte des loyers » de l'ANIL.
        <strong>C'est le loyer d'une location NON meublée, charges comprises</strong> : ce n'est
        donc pas une recette de meublé, seulement un point de comparaison avec le marché de la
        location vide. Il n'entre dans aucun calcul fiscal ni dans la simulation elle-même.
    </p>
    <p>
        Pour un bien à Paris, Lyon ou Marseille, le repère se lit par arrondissement, comme
        l'estimation DVF. Sans commune identifiée, ou pour une commune hors du périmètre de la
        source, le repère ne s'affiche simplement pas.
    </p>
    <p>
        Sur une instance tout juste installée ou mise à jour, le repère peut manquer quelques
        heures le temps de l'import automatique quotidien &mdash; rien à faire, il apparaît de
        lui-même dès que la commune du bien est connue.
    </p>
    <p>
        Le millésime affiché est celui réellement importé, avec un lien vers la fiche
        data.gouv.fr correspondante. La recherche du millésime suivant se fait automatiquement
        chaque jour, sans intervention &mdash; rien à relever ni mettre à jour à la main.
    </p>

    <div class="ctx-tip">
        <strong>Astuce :</strong> Utilisez la projection pluriannuelle pour anticiper le moment où le micro-BIC redeviendra plus intéressant (quand les amortissements seront épuisés).
    </div>
