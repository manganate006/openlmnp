    <h3>Travaux sur le bien</h3>
    <p>Les travaux réalisés sur votre bien locatif peuvent être amortis ou passés en charges selon leur nature.</p>

    <h3>Types de travaux</h3>
    <ul>
        <li data-icon="&#x2B06;"><strong>Travaux d'amélioration</strong> &mdash; Augmentent la valeur du bien (rénovation cuisine, salle de bain, isolation...). Amortis sur 10 à 15 ans.</li>
        <li data-icon="&#x1F527;"><strong>Travaux de réparation</strong> &mdash; Maintiennent le bien en état (remplacement chauffe-eau, peinture...). Passés en charges directes.</li>
    </ul>

    <h3>Informations à saisir</h3>
    <ul>
        <li data-icon="&#x1F4B5;"><strong>Montant TTC</strong> &mdash; Coût total des travaux</li>
        <li data-icon="&#x1F4C5;"><strong>Date</strong> &mdash; Date de réalisation ou de facturation</li>
        <li data-icon="&#x23F3;"><strong>Durée d'amortissement</strong> &mdash; Pour les travaux amortissables</li>
        <li data-icon="&#x1F4CE;"><strong>Justificatif</strong> &mdash; Facture de l'artisan ou du fournisseur</li>
    </ul>

    <h3>Travaux déjà amortis par un comptable</h3>
    <p>Si ces travaux figuraient déjà au plan d'amortissement de votre cabinet, dépliez la section <strong>« Reprise d'une comptabilité existante »</strong>, au bas du formulaire. Elle ne sert qu'une fois, à la première saisie.</p>
    <ul>
        <li data-icon="&#x1F4C9;"><strong>Dotation annuelle</strong> &mdash; laissez « Calculée (montant &divide; durée) » dans le cas normal. « Recopiée de ma liasse » fait apparaître le champ <strong>Dotation annuelle recopiée</strong> : vous y remettez le chiffre du tableau <strong>2033-C</strong>, et plus rien ne le recalcule ensuite. C'est ce qui permet de conserver l'arrondi de votre cabinet.</li>
        <li data-icon="&#x1F5C3;"><strong>Amortissements déjà pratiqués</strong> &mdash; le cumul au 31/12 du dernier exercice qu'il a tenu. Il s'ajoute au cumul du bilan (<strong>2033-A case 030</strong>) et à la colonne « amortissements » du <strong>2033-C</strong>, jamais à la charge de l'exercice.</li>
    </ul>

    <div class="ctx-warning">
        <strong>Le piège :</strong> « Amortissements déjà pratiqués » est un historique, pas une charge. Ne le renseignez que pour les exercices que vous ne saisirez <em>pas</em> ici. Si vous reprenez ces années dans l'application, laissez-le à 0 &mdash; sinon le cumul du bilan est gonflé deux fois.
    </div>

    <div class="ctx-tip">
        <strong>Astuce :</strong> Les travaux réalisés avant le début de l'activité de location peuvent aussi être amortis, à condition de les dater correctement.
    </div>
</div>
