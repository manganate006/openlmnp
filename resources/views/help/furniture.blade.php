    <h3>Gestion du mobilier</h3>
    <p>Enregistrez tous les meubles et équipements achetés pour votre location meublée.</p>

    <h3>Règle des 600 EUR</h3>
    <ul>
        <li data-icon="&#x2B06;"><strong>Plus de 600 EUR TTC</strong> &mdash; Le meuble est <strong>amorti</strong> sur sa durée de vie (généralement 5 à 10 ans)</li>
        <li data-icon="&#x2B07;"><strong>Moins de 600 EUR TTC</strong> &mdash; Le meuble passe directement en <strong>charge</strong> déductible l'année d'achat</li>
    </ul>

    <h3>Durées d'amortissement courantes</h3>
    <ul>
        <li data-icon="&#x1F6CB;"><strong>Literie, canapé</strong> &mdash; 10 ans</li>
        <li data-icon="&#x1F4FA;"><strong>Électroménager, TV</strong> &mdash; 5 à 7 ans</li>
        <li data-icon="&#x1FA91;"><strong>Petit mobilier</strong> &mdash; 5 ans</li>
        <li data-icon="&#x1F5A5;"><strong>Informatique</strong> &mdash; 3 ans</li>
    </ul>

    <h3>Mobilier déjà amorti par un comptable</h3>
    <p>Si ce meuble figurait déjà au plan d'amortissement de votre cabinet, dépliez la section <strong>« Reprise d'une comptabilité existante »</strong>, au bas du formulaire. Elle ne sert qu'une fois, à la première saisie.</p>
    <ul>
        <li data-icon="&#x1F4C9;"><strong>Dotation annuelle</strong> &mdash; laissez « Calculée (montant &divide; durée) » dans le cas normal. « Recopiée de ma liasse » fait apparaître le champ <strong>Dotation annuelle recopiée</strong> : vous y remettez le chiffre du tableau <strong>2033-C</strong>, et plus rien ne le recalcule ensuite. C'est ce qui permet de conserver l'arrondi de votre cabinet.</li>
        <li data-icon="&#x1F5C3;"><strong>Amortissements déjà pratiqués</strong> &mdash; le cumul au 31/12 du dernier exercice qu'il a tenu. Il s'ajoute au cumul du bilan (<strong>2033-A case 030</strong>) et à la colonne « amortissements » du <strong>2033-C</strong>, jamais à la charge de l'exercice.</li>
    </ul>
    <p>Un meuble entièrement amorti chez votre comptable se reprend quand même : saisissez-le avec son cumul, il figurera au bilan pour mémoire sans peser sur le résultat.</p>

    <div class="ctx-warning">
        <strong>Le piège :</strong> « Amortissements déjà pratiqués » est un historique, pas une charge. Ne le renseignez que pour les exercices que vous ne saisirez <em>pas</em> ici. Si vous reprenez ces années dans l'application, laissez-le à 0 &mdash; sinon le cumul du bilan est gonflé deux fois.
    </div>

    <div class="ctx-tip">
        <strong>Astuce :</strong> Pour un meuble proche de 600 EUR, il est parfois plus avantageux de le passer en charge directe plutôt qu'en amortissement.
    </div>
